#!/usr/bin/env node
// Import Lucy's combined Rive file from a gaia-research/lucy checkout.
//
//   node packages/site/scripts/import-lucy-live.mjs ~/lucy
//
// Copies viewer/candidates/lucy-<sha>.riv and its referenced sidecars
// (the lazily loaded states' images) to public/lucy-live/<sha>/, and writes
// src/lucy-scene/rive/lucyLiveManifest.ts: per-state placement inside the
// combined root artboard, so the site can register the canvas onto the
// static master it already frames.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, rmSync, existsSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..')
const LUCY = process.argv[2]
if (!LUCY) throw new Error('usage: import-lucy-live.mjs <path to gaia-research/lucy checkout>')
const C = join(LUCY, 'viewer/candidates')
const cand = JSON.parse(readFileSync(join(C, 'candidates.json'), 'utf8'))
const comb = cand.combined
if (!comb) throw new Error('no combined file in candidates.json (run rig/tools/combine.py + viewer/sync.mjs)')
const tag = comb.riv.replace(/^lucy-/, '').replace(/\.riv$/, '')
const outDir = join(SITE, 'public/lucy-live')
if (existsSync(outDir)) rmSync(outDir, { recursive: true })
mkdirSync(join(outDir, tag, 'assets'), { recursive: true })
copyFileSync(join(C, comb.riv), join(outDir, tag, 'lucy.riv'))
for (const f of readdirSync(join(C, comb.assets))) copyFileSync(join(C, comb.assets, f), join(outDir, tag, 'assets', f))

const states = {}
for (const s of comb.states) {
  const st = cand.states[s]
  const a = st.artboard // { w, h, pad, texScale } of the state's own artboard
  const p = comb.place[s] // where that artboard sits in the root: x, y, scale
  // the master's own rectangle inside the root artboard (root units)
  const mw = a.w / a.texScale - 2 * a.pad, mh = a.h / a.texScale - 2 * a.pad
  states[s] = {
    x: +(p.x + a.pad * a.texScale * p.scale).toFixed(3),
    y: +(p.y + a.pad * a.texScale * p.scale).toFixed(3),
    w: +(mw * a.texScale * p.scale).toFixed(3),
    h: +(mh * a.texScale * p.scale).toFixed(3),
    eager: (comb.eager || []).includes(s),
  }
}
const manifest = {
  source: `gaia-research/lucy@${cand.commit}`,
  riv: `lucy-live/${tag}/lucy.riv`,
  assets: `lucy-live/${tag}/assets/`,
  sha256: comb.sha256,
  bytes: comb.bytes,
  root: { w: comb.artboard[0], h: comb.artboard[1] },
  sidecars: comb.sidecarFiles,
  // each sidecar's size, so the site can show honest byte progress and plan
  // the fetch order (the entrance waits on Ultra's core tier, not its effects)
  sidecarBytes: Object.fromEntries(
    Object.entries(comb.sidecarFiles).map(([name, file]) => [name, statSync(join(C, comb.assets, file)).size]),
  ),
  states,
}
const ts = `// Generated by scripts/import-lucy-live.mjs from ${manifest.source}. Do not edit by hand.
// Lucy's combined Rive file: four states in one root artboard ("Lucy"), switched
// by the view model "Lucy" enum property "state". Heaven's images are embedded;
// the other states' images are referenced sidecars, fetched after first paint.
// sidecarBytes[name] is each sidecar's size, so the site can show honest byte progress.
// states[s] is the state's master rectangle inside the root artboard (root units).
export const LUCY_LIVE = ${JSON.stringify(manifest, null, 2)} as const
`
writeFileSync(join(SITE, 'src/lucy-scene/rive/lucyLiveManifest.ts'), ts)
console.log(`imported ${comb.riv} (${comb.bytes} B) + ${readdirSync(join(C, comb.assets)).length} sidecars -> public/lucy-live/${tag}/`)
